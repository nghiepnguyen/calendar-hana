"""G1-SOIL Stage 2: field-by-field classification of the stale historical artifact
docs/audits/sources/p4-vol10/jiesha-overlap-impact-v1/raw.json (env-gated JIESHA_IMPACT_FULL suite).

    python3 -I docs/audits/sources/p4-vol10/g1-soil-stage2/classify_overlap_impact.py DIR [--write]

DIR holds the artifact regenerated by `JIESHA_IMPACT_FULL=1 npx vitest run shared/lunar/p4JieshaOverlapImpact.test.ts`
on worktrees of f3c68c6 (pre-G1-glyph), d5c005f (pre-G1-SOIL) and this branch (v4), as f3c68c6.json,
d5c005f.json, v4.json; the locked bytes are read from git HEAD. The difference locked → v4 is decomposed into
steps locked → f3c68c6 → d5c005f → v4, and every changed leaf is classified by step, section, activity / event,
and field. Writes overlap-impact-classification.json; default verifies it. The locked artifact is not touched.
"""
import hashlib
import json
import subprocess
import sys
from collections import Counter
from datetime import date, timedelta
from pathlib import Path

OUT = Path('docs/audits/sources/p4-vol10/g1-soil-stage2/overlap-impact-classification.json')
ART = 'docs/audits/sources/p4-vol10/jiesha-overlap-impact-v1/raw.json'
CAL = Path('docs/audits/sources/p4-vol10/g1-soil-stage1/soil-calendar.json')
SCOPE = Path('docs/audits/sources/p4-vol10/puzhu17-bujiang-v1/scope-dates.json')
SOIL = ['丑-甲寅', '丑-丙寅', '丑-壬寅', '丑-戊寅', '未-戊申']
DOMAIN = ('2025-01-01', '2027-12-31')


def leaves(day):
    """Flatten one day into {path: value}: logs as multisets, activities / events keyed by id."""
    out = {}
    for scope, block in (('top', day), ('A', day.get('A', {})), ('B', day.get('B', {}))):
        for log in ('p4Log', 'vol10Log'):
            for e in block.get(log, []):
                who = e.get('activityId') or e.get('heading')
                k = (scope, log, who, json.dumps({x: y for x, y in e.items() if x != 'date'}, ensure_ascii=False))
                out[k] = out.get(k, 0) + 1
        if scope == 'top':
            continue
        for a in block.get('activities', []):
            for f, v in a.items():
                if f != 'activityId':
                    out[(scope, 'activities', a['activityId'], f)] = json.dumps(v, ensure_ascii=False)
        for e in block.get('events', []):
            for f, v in e.items():
                if f != 'id':
                    out[(scope, 'events', e['id'], f)] = json.dumps(v, ensure_ascii=False)
        for i, h in enumerate(block.get('headings', [])):
            out[(scope, 'headings', str(i), 'row')] = json.dumps(h, ensure_ascii=False)
    return out


def step(a, b):
    da = {d['date']: d for d in a['days']}
    db = {d['date']: d for d in b['days']}
    dates, fields, who = set(), Counter(), Counter()
    for dt in sorted(set(da) | set(db)):
        la, lb = leaves(da.get(dt, {})), leaves(db.get(dt, {}))
        changed = [k for k in set(la) | set(lb) if la.get(k) != lb.get(k)]
        if changed:
            dates.add(dt)
        for k in changed:
            fields[f'{k[0]}.{k[1]}' + (f'.{k[3]}' if k[1] in ('activities', 'events') else '')] += 1
            who[f'{k[1]}:{k[2]}'] += 1
    return dates, fields, who


def main(d):
    locked = json.loads(subprocess.run(['git', 'show', f'HEAD:{ART}'], capture_output=True, check=True).stdout)
    files = {'f3c68c6': json.loads((d / 'f3c68c6.json').read_text(encoding='utf-8')),
             'd5c005f': json.loads((d / 'd5c005f.json').read_text(encoding='utf-8')),
             'v4': json.loads((d / 'v4.json').read_text(encoding='utf-8'))}
    inside = set()
    for ws in json.loads(CAL.read_text(encoding='utf-8'))['windows'].values():
        for w in ws:
            x = date.fromisoformat(w['onset'])
            while x <= date.fromisoformat(w['eve']):
                inside.add(x.isoformat())
                x += timedelta(1)
    scope = json.loads(SCOPE.read_text(encoding='utf-8'))
    soil_inside = {x for c in SOIL for x in scope[c] if x in inside}
    steps = {}
    for name, a, b in (('locked→f3c68c6 (pre-existing, before G1 glyph)', locked, files['f3c68c6']),
                       ('f3c68c6→d5c005f (G1 glyph Stage 2, authority v3)', files['f3c68c6'], files['d5c005f']),
                       ('d5c005f→v4 (G1-SOIL Stage 2, authority v4)', files['d5c005f'], files['v4'])):
        dates, fields, who = step(a, b)
        steps[name] = {'changedDates': len(dates), 'fields': dict(sorted(fields.items())),
                       'byActivityOrEvent': dict(sorted(who.items())),
                       **({'datesEqualSoilInside': dates == soil_inside,
                           'domainDates': sorted(x for x in dates if DOMAIN[0] <= x <= DOMAIN[1]),
                           'onlyDemolition': set(k.split(':', 1)[1] for k in who) <= {'demolition'}}
                          if name.startswith('d5c005f') else {})}
    doc = {
        'version': 'g1-soil-stage2-overlap-impact-classification-v1',
        'artifact': ART,
        'inputs': {'locked(HEAD)': hashlib.sha256(json.dumps(locked).encode()).hexdigest()[:16],
                   **{k: hashlib.sha256((d / f'{k}.json').read_bytes()).hexdigest() for k in files}},
        'soilInsideOccurrences': len(soil_inside),
        'steps': steps,
        'policy': 'historical artifact kept as locked; regenerated outputs are comparison evidence only',
    }
    text = json.dumps(doc, ensure_ascii=False, indent=1) + '\n'
    if '--write' in sys.argv:
        OUT.write_text(text, encoding='utf-8')
    else:
        assert OUT.read_text(encoding='utf-8') == text, 'overlap-impact-classification.json differs'
    print(json.dumps({k: {x: v[x] for x in v if x not in ('fields',)} for k, v in steps.items()}, ensure_ascii=False)[:3000])
    print(json.dumps({k: v['fields'] for k, v in steps.items()}, ensure_ascii=False)[:3000])


if __name__ == '__main__':
    main(Path(sys.argv[1]))
