// Derives shared/astronomy/solarTerms/authority.data.ts from the frozen
// golden-v4 JPL authority dataset. Deterministic: same frozen input, same
// bytes. Never recomputes astronomy; it only re-encodes the reviewed TT ms.
//
//   node scripts/generate-solar-term-authority.mjs          write the data file
//   node scripts/generate-solar-term-authority.mjs --check  fail if it differs

import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

export const GENERATOR_VERSION = 'solar-term-authority-runtime-generator 1.0.0'
export const SOURCE_PATH = 'golden-v4/astronomy/solar-terms-jpl-de440s-clock-v1.json'
export const MANIFEST_PATH = 'golden-v4/manifest.json'
export const OUTPUT_PATH = 'shared/astronomy/solarTerms/authority.data.ts'
const FIRST_YEAR = 1899
const LAST_YEAR = 2101

const q = (value) => {
  if (/['\\\n]/.test(value)) throw new Error('unexpected character in metadata')
  return `'${value}'`
}
const sha256 = (data) => createHash('sha256').update(data).digest('hex')

/** Returns { text, encoded, encodedSha256, sourceSha256, rows } or throws. */
export function renderAuthorityData(root = '.') {
  const source = readFileSync(`${root}/${SOURCE_PATH}`)
  const manifest = JSON.parse(readFileSync(`${root}/${MANIFEST_PATH}`, 'utf8'))
  const sourceSha256 = sha256(source)
  const pinned = manifest.files[SOURCE_PATH]?.sha256
  if (manifest.status !== 'REVIEWED_FROZEN' || pinned !== sourceSha256)
    throw new Error(`authority source does not match the frozen golden-v4 manifest`)
  const doc = JSON.parse(source.toString('utf8'))
  if (
    doc.reviewStatus !== 'REVIEWED_FROZEN' ||
    doc.timeScale !== 'TT' ||
    doc.clockPolicy !== 'clock-v1' ||
    doc.rowFormat?.[3] !== 'ttMs (canonical T)'
  )
    throw new Error('unexpected authority dataset contract')
  const rows = doc.rows.map((row) => row.split('|'))
  if (rows.length !== (LAST_YEAR - FIRST_YEAR + 1) * 24) throw new Error('unexpected row count')
  const ttMs = rows.map((r, i) => {
    if (+r[0] !== FIRST_YEAR + Math.floor(i / 24) || +r[1] !== (19 + (i % 24)) % 24)
      throw new Error(`row ${i} out of order`)
    if (!/^-?\d+$/.test(r[3])) throw new Error(`row ${i} T is not an integer`)
    const t = Number(r[3])
    if (!Number.isSafeInteger(t) || String(t) !== r[3]) throw new Error(`row ${i} T unsafe`)
    return t
  })
  const parts = [ttMs[0].toString(36)]
  for (let i = 1; i < ttMs.length; i++) {
    const delta = ttMs[i] - ttMs[i - 1]
    if (delta <= 0) throw new Error(`row ${i} not strictly increasing`)
    parts.push(delta.toString(36))
  }
  const encoded = parts.join(',')
  const encodedSha256 = sha256(encoded)
  const text = `// GENERATED by scripts/generate-solar-term-authority.mjs. Do not edit by hand.
// Source: ${SOURCE_PATH} (golden-v4, REVIEWED_FROZEN).
// Canonical T per crossing as integer TT ms since J2000.0 TT, rows ordered by
// year ${FIRST_YEAR}–${LAST_YEAR} and term index (19, 20, …, 18). Encoding: first T
// in base 36, then strictly positive base-36 deltas, comma-separated.

export const AUTHORITY_DATA = {
  authorityVersion: ${q(doc.authorityVersion)},
  datasetId: ${q(doc.datasetId)},
  clockVersion: ${q(doc.clockPolicy)},
  timeScale: 'TT',
  generatorVersion: ${q(GENERATOR_VERSION)},
  sourcePath: ${q(SOURCE_PATH)},
  sourceSha256: ${q(sourceSha256)},
  firstYear: ${FIRST_YEAR},
  lastYear: ${LAST_YEAR},
  rowCount: ${ttMs.length},
  encodedSha256: ${q(encodedSha256)},
  encoded:
    ${q(encoded)},
} as const
`
  return { text, encoded, encodedSha256, sourceSha256, ttMs }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { text, encodedSha256 } = renderAuthorityData()
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUTPUT_PATH, 'utf8')
    if (current !== text) {
      console.error(`${OUTPUT_PATH} differs from the generator output`)
      process.exit(1)
    }
    console.log(`${OUTPUT_PATH} up to date (${encodedSha256})`)
  } else {
    writeFileSync(OUTPUT_PATH, text)
    console.log(`wrote ${OUTPUT_PATH} (${encodedSha256})`)
  }
}
