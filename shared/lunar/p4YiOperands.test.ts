import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import authority from '../almanac-data/p4-yi-operands-v1.json'
import golden from '../almanac-data/golden-p4-yi-operands-v1.json'
import sourceLock from '../../docs/audits/sources/p4-vol10/yi-freeze-v1/lock.json'
import { lockedDigests } from './lockAnchor'
import { evaluateP4YiOperand } from './p4YiOperands'

type PresenceFixture = {
  id: string
  han: string
  categories: string[]
  requestName: string
  inputs: Record<string, unknown>
  providerStates: Record<string, unknown>
  inputProvenance: Record<string, unknown>
  expected: {
    outcome: 'present' | 'absent' | 'unknown'
    canonicalHan: string
    authorityId: string
    ruleId: string
    authorityStatus: string
    sourceRefs: number[]
  }
  derivation: { sourceRefs: number[]; calculation: string }
}

const HAN = ['母倉', '福德', '天恩', '天巫', '天后', '天醫', '除神', '驛馬', '天馬', '吉期', '鳴吠']
const bytes = (path: string) => readFileSync(path)
const digest = (path: string, algorithm = 'sha256') =>
  createHash(algorithm).update(bytes(path)).digest('hex')
const presenceBlock = golden.blocks.find((block) => block.kind === 'presence')!
// Expected is read from the immutable block, never generated by the provider under test.
const frozen = JSON.parse(bytes(presenceBlock.path).toString('utf8')) as {
  presenceFixtures: PresenceFixture[]
}
const fixtures = frozen.presenceFixtures
// 4.2 owns resolved presence/boundary fixtures; the 78 unknown cases belong to 4.3.
const resolved = fixtures.filter((fixture) => fixture.expected.outcome !== 'unknown')
const sourceSlices = authority.entries.flatMap((entry) =>
  entry.sources.map((source, sourceRef) => ({ han: entry.han, sourceRef, ...source })),
)
const rawPaths = [...new Set(sourceSlices.map((source) => source.path))]
const rawText = new Map(rawPaths.map((path) => [path, bytes(path).toString('utf8')]))

describe('P4-C 4.2 frozen authority, Golden and raw offsets', () => {
  it('pins the pre-implementation source lock and Golden index independently', () => {
    expect(digest('docs/audits/sources/p4-vol10/yi-freeze-v1/lock.json')).toBe(
      'a66f8984471f736a3f73ca087db44213dc42b356814750d1941418be6e054c12',
    )
    expect(digest('shared/almanac-data/golden-p4-yi-operands-v1.json')).toBe(
      'ba5544c3e7b0bd540acfff8a673ab22c0c4b78dc8680c18d18cea07523f797d1',
    )
    expect(sourceLock.files).toHaveLength(677)
    // Pinned files checked as committed at the lock's anchor (owner rule 2026-10-17, see lockAnchor.ts).
    const atFreeze = lockedDigests(
      'docs/audits/sources/p4-vol10/yi-freeze-v1/lock.json',
      sourceLock.files.map((file) => file.path),
    )
    for (const file of sourceLock.files)
      expect(atFreeze.get(file.path), file.path).toBe(file.sha256)
    expect(digest(golden.authority.path)).toBe(golden.authority.sha256)
    for (const block of golden.blocks) expect(digest(block.path), block.path).toBe(block.sha256)
  })

  it('keeps exactly 11 entries and the frozen fixture selection with source derivations', () => {
    expect(authority.entries.map((entry) => entry.han)).toEqual(HAN)
    expect(presenceBlock.selector).toBe('presenceFixtures')
    expect(fixtures).toHaveLength(presenceBlock.count)
    expect(fixtures).toHaveLength(906)
    expect(new Set(fixtures.map((fixture) => fixture.id)).size).toBe(906)
    expect(resolved).toHaveLength(828)
    expect(fixtures.filter((fixture) => fixture.expected.outcome === 'unknown')).toHaveLength(78)
    for (const han of HAN) {
      const cases = resolved.filter((fixture) => fixture.han === han)
      expect(
        cases.some((fixture) => fixture.expected.outcome === 'present'),
        han,
      ).toBe(true)
      expect(
        cases.some((fixture) => fixture.expected.outcome === 'absent'),
        han,
      ).toBe(true)
      expect(
        cases.some((fixture) => fixture.categories.includes('boundary')),
        han,
      ).toBe(true)
    }
    for (const fixture of fixtures) {
      const entry = authority.entries.find((candidate) => candidate.han === fixture.han)!
      expect(entry, fixture.id).toBeDefined()
      expect(fixture.expected, fixture.id).toMatchObject({
        canonicalHan: entry.han,
        authorityId: entry.authorityId,
        ruleId: entry.ruleId,
        authorityStatus: entry.status,
      })
      expect(fixture.derivation.calculation.length, fixture.id).toBeGreaterThan(0)
      expect(fixture.expected.sourceRefs, fixture.id).toEqual(fixture.derivation.sourceRefs)
      for (const ref of fixture.expected.sourceRefs) {
        expect(Number.isInteger(ref), fixture.id).toBe(true)
        expect(ref, fixture.id).toBeGreaterThanOrEqual(0)
        expect(ref, fixture.id).toBeLessThan(entry.sources.length)
      }
    }
  })

  it.each(rawPaths)('keeps raw bytes and SHA-1: %s', (path) => {
    const refs = sourceSlices.filter((source) => source.path === path)
    expect(new Set(refs.map((source) => source.sha1)).size).toBe(1)
    expect(digest(path, 'sha1')).toBe(refs[0]!.sha1)
  })

  it('counts supplementary Han as one Unicode code point, independently of UTF-16', () => {
    const text = '甲𠀀乙𠀁丙'
    expect(Array.from(text).slice(1, 4).join('')).toBe('𠀀乙𠀁')
    expect(text.slice(1, 4)).not.toBe('𠀀乙𠀁')
    expect(sourceSlices).toHaveLength(74)
  })

  it.each(sourceSlices)('$han source[$sourceRef] reproduces its exact raw quote', (source) => {
    const points = Array.from(rawText.get(source.path)!)
    expect(Number.isInteger(source.offset)).toBe(true)
    expect(Number.isInteger(source.length)).toBe(true)
    expect(source.offset).toBeGreaterThanOrEqual(0)
    expect(source.length).toBeGreaterThan(0)
    expect(source.offset + source.length).toBeLessThanOrEqual(points.length)
    expect(Array.from(source.quote)).toHaveLength(source.length)
    expect(points.slice(source.offset, source.offset + source.length).join('')).toBe(source.quote)
  })
})

describe('P4-C 4.2 source-derived resolved presence', () => {
  // Plain assertions must stay red until 4.4 implements the real provider.
  // No mocks, it.fails, skips, missing-module fallbacks or expected rewrites.
  it.each(resolved)('$id -> $expected.outcome', (fixture) => {
    const result = evaluateP4YiOperand(
      fixture.requestName,
      fixture.inputs,
      fixture.providerStates,
      fixture.inputProvenance,
    )
    expect(result.presence, fixture.id).toBe(fixture.expected.outcome)
  })
})
